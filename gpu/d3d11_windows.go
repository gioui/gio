package gpu

import (
	"errors"
	"fmt"
	"image"
	"image/color"

	backend "gioui.org/gpu/internal/d3d11"
	"gioui.org/internal/d3d11"
)

// D3D11Format is a DXGI format value.
type D3D11Format = uint32

// The formats a custom pass is likely to need. BC formats hold the block
// compressed data found in most game texture archives, so their contents can
// be uploaded without decoding them on the CPU.
const (
	FormatR8G8B8A8UNorm     D3D11Format = 28
	FormatR8G8B8A8UNormSRGB D3D11Format = 29
	FormatD32Float          D3D11Format = 40
	FormatBC1UNorm          D3D11Format = 71
	FormatBC1UNormSRGB      D3D11Format = 72
	FormatBC2UNorm          D3D11Format = 74
	FormatBC2UNormSRGB      D3D11Format = 75
	FormatBC3UNorm          D3D11Format = 77
	FormatBC3UNormSRGB      D3D11Format = 78
	FormatBC4UNorm          D3D11Format = 80
	FormatBC4SNorm          D3D11Format = 81
	FormatBC5UNorm          D3D11Format = 83
	FormatBC5SNorm          D3D11Format = 84
	FormatBC7UNorm          D3D11Format = 98
	FormatBC7UNormSRGB      D3D11Format = 99
)

// D3D11VertexFormat is the DXGI format of a vertex attribute.
type D3D11VertexFormat = uint32

const (
	VertexFormatFloat32   D3D11VertexFormat = 41 // R32_FLOAT
	VertexFormatFloat32x2 D3D11VertexFormat = 16 // R32G32_FLOAT
	VertexFormatFloat32x3 D3D11VertexFormat = 6  // R32G32B32_FLOAT
	VertexFormatFloat32x4 D3D11VertexFormat = 2  // R32G32B32A32_FLOAT
	VertexFormatUNorm8x4  D3D11VertexFormat = 28 // R8G8B8A8_UNORM
	VertexFormatUInt16    D3D11VertexFormat = 57 // R16_UINT
	VertexFormatFloat16x4 D3D11VertexFormat = 10 // R16G16B16A16_FLOAT
	VertexFormatUNorm10x2 D3D11VertexFormat = 24 // R10G10B10A2_UNORM
)

// D3D11CullMode selects which triangle windings are discarded.
type D3D11CullMode int

const (
	CullNone D3D11CullMode = iota
	CullFront
	CullBack
)

// D3D11BufferKind is what a buffer is bound as.
type D3D11BufferKind int

const (
	// VertexBuffer holds interleaved vertex attributes.
	VertexBuffer D3D11BufferKind = iota
	// IndexBuffer holds 16 bit vertex indices.
	IndexBuffer
	// ConstantBuffer holds uniforms.
	ConstantBuffer
)

// D3D11 is a handle on the Direct3D 11 backend of a GPU. It draws on the same
// device and immediate context Gio itself uses, so passes issued through it
// are ordered with respect to Gio's frame without any synchronization, and
// textures can be handed to Gio without a copy.
type D3D11 struct {
	b *backend.Backend
	// Rasterizer state of the last pipeline bound, applied by SetPipeline.
	cull       D3D11CullMode
	depthTest  bool
	depthWrite bool
}

// D3D11 returns a handle for issuing custom Direct3D 11 drawing commands. It
// reports an error if the GPU is not backed by Direct3D 11.
func (g *gpu) D3D11() (*D3D11, error) {
	b, ok := g.ctx.(*backend.Backend)
	if !ok {
		return nil, errors.New("gpu: the current backend is not Direct3D 11")
	}
	return &D3D11{b: b}, nil
}

// CompileHLSL compiles HLSL source to DXBC bytecode with the shader compiler
// that ships with Windows. The result can be passed to NewPipeline. Compiling
// takes milliseconds, so cache the result if a pipeline is created often.
func (d *D3D11) CompileHLSL(source, entry, target string) ([]byte, error) {
	return d3d11.CompileHLSL(source, entry, target, d3d11.D3DCOMPILE_OPTIMIZATION_LEVEL3)
}

// D3D11TextureDesc describes a texture.
type D3D11TextureDesc struct {
	Width, Height int
	// MipLevels is 0 for a single level. Mip levels are uploaded explicitly;
	// they are never generated by the GPU.
	MipLevels int
	Format    D3D11Format
	// RenderTarget allows drawing into the texture.
	RenderTarget bool
	// Depth makes the texture a depth buffer.
	Depth bool
	// Sampled allows reading the texture in a shader.
	Sampled bool
}

// D3D11Texture is a texture owned by the caller.
type D3D11Texture struct {
	t *backend.RawTexture
}

// NewTexture creates a texture.
func (d *D3D11) NewTexture(desc D3D11TextureDesc) (*D3D11Texture, error) {
	t, err := d.b.NewRawTexture(backend.RawTextureDesc{
		Width:        desc.Width,
		Height:       desc.Height,
		MipLevels:    desc.MipLevels,
		Format:       desc.Format,
		RenderTarget: desc.RenderTarget,
		Depth:        desc.Depth,
		Sampled:      desc.Sampled,
	})
	if err != nil {
		return nil, err
	}
	return &D3D11Texture{t: t}, nil
}

// UploadMip copies raw, already encoded, data into one mip level. For block
// compressed formats the data must be the blocks as stored in the file.
func (t *D3D11Texture) UploadMip(level int, data []byte) error {
	return t.t.UploadMip(level, data)
}

// MipSize returns the number of bytes one mip level occupies.
func (t *D3D11Texture) MipSize(level int) int {
	return t.t.MipSize(level)
}

// Bounds returns the size of the texture in pixels.
func (t *D3D11Texture) Bounds() image.Rectangle {
	return image.Rect(0, 0, t.t.Width(), t.t.Height())
}

// Clear fills the render target with a colour.
func (t *D3D11Texture) Clear(r, g, b, a float32) {
	t.t.Clear(r, g, b, a)
}

// ClearDepth resets the depth buffer to value.
func (t *D3D11Texture) ClearDepth(value float32) {
	t.t.ClearDepth(value)
}

// ReadPixels copies the texture back to the CPU as tightly packed rows. It is
// meant for tests and diagnostics.
func (t *D3D11Texture) ReadPixels() ([]byte, error) {
	return t.t.ReadPixels()
}

// ReadPixelsMip is ReadPixels for one named mip level, which is how a caller
// checks that a level was written where it said it was.
func (t *D3D11Texture) ReadPixelsMip(level int) ([]byte, error) {
	return t.t.ReadPixelsMip(level)
}

// Release frees the texture and its views. Painting a released texture
// panics.
func (t *D3D11Texture) Release() {
	if t == nil {
		return
	}
	t.t.Release()
}

func bytesPerPixel(format D3D11Format) int {
	switch format {
	case FormatBC1UNorm, FormatBC1UNormSRGB:
		return 1
	}
	return 4
}

// D3D11Buffer is a buffer owned by the caller.
type D3D11Buffer struct {
	b *backend.RawBuffer
}

// NewBuffer creates a buffer of size bytes. Dynamic buffers are updated every
// frame and should not be larger than necessary.
func (d *D3D11) NewBuffer(kind D3D11BufferKind, size int, dynamic bool) (*D3D11Buffer, error) {
	var bind uint32
	switch kind {
	case VertexBuffer:
		bind = d3d11.BIND_VERTEX_BUFFER
	case IndexBuffer:
		bind = d3d11.BIND_INDEX_BUFFER
	case ConstantBuffer:
		bind = d3d11.BIND_CONSTANT_BUFFER
	default:
		return nil, fmt.Errorf("gpu: unknown buffer kind %d", kind)
	}
	b, err := d.b.NewRawBuffer(bind, size, dynamic)
	if err != nil {
		return nil, err
	}
	return &D3D11Buffer{b: b}, nil
}

// Upload copies data into the buffer.
func (b *D3D11Buffer) Upload(data []byte) error {
	return b.b.Upload(data)
}

// ReadBytes copies the buffer back to the CPU. It is meant for tests and
// diagnostics.
func (b *D3D11Buffer) ReadBytes() ([]byte, error) {
	return b.b.ReadBytes()
}

// Release frees the buffer.
func (b *D3D11Buffer) Release() {
	if b == nil {
		return
	}
	b.b.Release()
}

// D3D11Input describes one vertex attribute of a pipeline.
type D3D11Input struct {
	// Semantic is the HLSL semantic, for example "POSITION" or "TEXCOORD".
	Semantic string
	// Index disambiguates repeated semantics.
	Index  uint32
	Format D3D11VertexFormat
	// Offset is the byte offset of the attribute within a vertex.
	Offset int
}

// D3D11PipelineDesc describes a shader pair and the vertex layout it expects.
type D3D11PipelineDesc struct {
	// Vertex and Fragment are DXBC bytecode, for example from CompileHLSL.
	Vertex   []byte
	Fragment []byte
	// Inputs describes the interleaved vertex attributes.
	Inputs []D3D11Input
	// Stride is the size of one vertex in bytes.
	Stride int
	// Cull selects which windings to discard.
	Cull D3D11CullMode
	// DepthTest tests fragments against the bound depth buffer.
	DepthTest bool
	// DepthWrite writes the depth of drawn fragments.
	DepthWrite bool
}

// D3D11Pipeline is a compiled shader pair owned by the caller.
type D3D11Pipeline struct {
	p *backend.RawPipeline
}

// NewPipeline compiles a pipeline.
func (d *D3D11) NewPipeline(desc D3D11PipelineDesc) (*D3D11Pipeline, error) {
	inputs := make([]backend.RawVertexInput, len(desc.Inputs))
	for i, in := range desc.Inputs {
		inputs[i] = backend.RawVertexInput{
			Semantic:      in.Semantic,
			SemanticIndex: in.Index,
			Format:        in.Format,
			Offset:        in.Offset,
		}
	}
	p, err := d.b.NewRawPipeline(desc.Vertex, desc.Fragment, inputs, desc.Stride)
	if err != nil {
		return nil, err
	}
	d.cull = desc.Cull
	d.depthTest = desc.DepthTest
	d.depthWrite = desc.DepthWrite
	return &D3D11Pipeline{p: p}, nil
}

// Release frees the pipeline.
func (p *D3D11Pipeline) Release() {
	if p == nil {
		return
	}
	p.p.Release()
}

// BeginPass binds the render targets and sets the viewport. When clear is set,
// the color target is filled with clearColor and the depth buffer is reset to
// one. Call EndPass when done.
func (d *D3D11) BeginPass(target, depth *D3D11Texture, viewport image.Rectangle, clear bool, clearColor color.NRGBA) {
	c := [4]float32{
		float32(clearColor.R) / 0xff,
		float32(clearColor.G) / 0xff,
		float32(clearColor.B) / 0xff,
		float32(clearColor.A) / 0xff,
	}
	d.b.BeginRawPass(rawOf(target), rawOf(depth), viewport, clear, c)
}

// EndPass releases the render targets. Gio binds its own before drawing, so
// this is only a courtesy to callers inspecting the device.
func (d *D3D11) EndPass() {
	d.b.BeginRawPass(nil, nil, image.Rectangle{}, false, [4]float32{})
}

// SetPipeline binds a pipeline and the rasterizer and depth state it was
// created with.
func (d *D3D11) SetPipeline(p *D3D11Pipeline) {
	d.b.SetRawState(backend.RawState{
		Cull:       cullMode(d.cull),
		DepthTest:  d.depthTest,
		DepthWrite: d.depthWrite,
	})
	d.b.SetRawPipeline(p.p)
}

// SetTexture binds a texture to a pixel shader slot.
func (d *D3D11) SetTexture(unit int, t *D3D11Texture) {
	d.b.SetRawTexture(unit, rawOf(t))
}

// SetUniforms binds a constant buffer to the first constant buffer slot of
// both shader stages.
func (d *D3D11) SetUniforms(b *D3D11Buffer) {
	if b == nil {
		return
	}
	d.b.SetRawConstantBuffer(b.b)
}

// SetVertexBuffer binds the vertex buffer, starting at offset bytes.
func (d *D3D11) SetVertexBuffer(b *D3D11Buffer, offset int) {
	d.b.SetRawVertexBuffer(b.b, offset)
}

// SetIndexBuffer binds the index buffer.
func (d *D3D11) SetIndexBuffer(b *D3D11Buffer) {
	d.b.SetRawIndexBuffer(b.b)
}

// DrawIndexed draws count indices from the bound index buffer.
func (d *D3D11) DrawIndexed(count int) {
	d.b.DrawRawIndexed(count)
}

func rawOf(t *D3D11Texture) *backend.RawTexture {
	if t == nil {
		return nil
	}
	return t.t
}

func cullMode(c D3D11CullMode) uint32 {
	switch c {
	case CullFront:
		return d3d11.CULL_FRONT
	case CullBack:
		return d3d11.CULL_BACK
	}
	return d3d11.CULL_NONE
}

// D3D11Device is implemented by a GPU whose backend is Direct3D 11. It is used
// to reach the custom drawing API from an app.Window or a headless.Window,
// which own the GPU.
type D3D11Device interface {
	D3D11() (*D3D11, error)
}
